#!/usr/bin/env node
/**
 * Generate the complete endpoint index in docs/API-REFERENCE.md from
 * docs/openapi.yaml.
 *
 * Why this exists: API-REFERENCE.md was hand-written and had drifted to 128 of
 * the spec's 718 paths — it claimed "Total Endpoints: 130". Every documented
 * route did exist in the spec, so nothing was wrong; 590 routes were simply
 * never written down. A hand-maintained list cannot keep up with a router that
 * registers 862 operations, so the list is generated instead.
 *
 * The hand-written prose above the sentinel is preserved verbatim. Everything
 * below it is replaced on every run, which is also what makes `--check`
 * meaningful: if the router changes and nobody regenerates, CI fails.
 *
 * No YAML dependency, matching generate-openapi.mjs — the spec is machine
 * generated with a fixed two-space structure, so line parsing is exact here.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = join(ROOT, "docs", "openapi.yaml");
const DOC = join(ROOT, "docs", "API-REFERENCE.md");
const asCheck = process.argv.includes("--check");

const BEGIN = "<!-- BEGIN GENERATED ENDPOINT_INDEX -->";
const END = "<!-- END GENERATED_ENDPOINT_INDEX -->";
const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete", "head", "options"]);

// ── Read the spec ─────────────────────────────────────────────────────────────
const specLines = readFileSync(SPEC, "utf8").split("\n");
const pathsStart = specLines.findIndex((line) => line === "paths:");
const componentsStart = specLines.findIndex((line) => line === "components:");
if (pathsStart < 0 || componentsStart < 0 || componentsStart < pathsStart) {
  console.error("generate-api-reference: docs/openapi.yaml must contain top-level `paths:` and `components:`.");
  process.exit(1);
}

/** @type {Array<{path: string, method: string, tag: string, summary: string, source: string, schema: string}>} */
const operations = [];
let currentPath = null;
let current = null;

for (const line of specLines.slice(pathsStart + 1, componentsStart)) {
  const pathMatch = /^ {2}(\/[^:]*):$/.exec(line);
  if (pathMatch) {
    currentPath = pathMatch[1];
    current = null;
    continue;
  }
  if (currentPath === null) continue;

  const methodMatch = /^ {4}([a-z]+):$/.exec(line);
  if (methodMatch && HTTP_METHODS.has(methodMatch[1])) {
    current = { path: currentPath, method: methodMatch[1].toUpperCase(), tag: "other", summary: "", source: "", schema: "" };
    operations.push(current);
    continue;
  }
  if (current === null) continue;

  const tagMatch = /^ {6}tags: \[([^\]]*)\]/.exec(line);
  if (tagMatch) current.tag = tagMatch[1].split(",")[0].trim() || "other";
  const summaryMatch = /^ {6}summary: (.+)$/.exec(line);
  if (summaryMatch) current.summary = summaryMatch[1].trim().replace(/^["']|["']$/g, "");
  const sourceMatch = /^ {6}x-source: (.+)$/.exec(line);
  if (sourceMatch) current.source = sourceMatch[1].trim();
  const schemaMatch = /^ {6}x-schema-status: (.+)$/.exec(line);
  if (schemaMatch) current.schema = schemaMatch[1].trim();
}

if (operations.length === 0) {
  console.error("generate-api-reference: parsed zero operations from the spec — the parser has drifted.");
  process.exit(1);
}

// ── Build the generated block ─────────────────────────────────────────────────
const byTag = new Map();
for (const op of operations) {
  if (!byTag.has(op.tag)) byTag.set(op.tag, []);
  byTag.get(op.tag).push(op);
}
const paths = new Set(operations.map((op) => op.path));
const unspecified = operations.filter((op) => op.schema === "unspecified").length;
const specified = operations.length - unspecified;

const out = [
  BEGIN,
  "<!--",
  "  GENERATED by scripts/generate-api-reference.mjs from docs/openapi.yaml.",
  "  Do not edit below this banner — run `npm run docs:api-reference` instead.",
  "  `npm run docs:openapi:check` fails if this section is stale.",
  "-->",
  "",
  `**${operations.length} operations across ${paths.size} paths.** ${specified} carry hand-written`,
  `request and response schemas; the other ${unspecified} carry \`x-schema-status: unspecified\`,`,
  "which means \"unknown\", not \"empty\" — read the linked source file for those.",
  "",
];

for (const tag of [...byTag.keys()].sort()) {
  const ops = byTag.get(tag).sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  out.push(`### ${tag} (${ops.length})`, "");
  out.push("| Method | Path | Source |", "| --- | --- | --- |");
  for (const op of ops) {
    const source = op.source ? `\`${op.source.replace(/^apps\/control-api\/src\//, "…/")}\`` : "—";
    out.push(`| \`${op.method}\` | \`${op.path}\` | ${source} |`);
  }
  out.push("");
}
out.push(END);

// ── Splice into the document ──────────────────────────────────────────────────
const doc = readFileSync(DOC, "utf8");
const begin = doc.indexOf(BEGIN);
const end = doc.indexOf(END);
let next;
if (begin >= 0 && end > begin) {
  next = doc.slice(0, begin) + out.join("\n") + doc.slice(end + END.length);
} else {
  next = `${doc.replace(/\n*$/, "")}\n\n${out.join("\n")}\n`;
}

// The hand-written overview states an endpoint count; keep it honest.
next = next.replace(/\*\*Total Endpoints:\*\*[^\n]*/, `**Total Endpoints:** ${operations.length} operations / ${paths.size} paths`);
next = next.replace(
  /^All endpoints require a `tenantId` query parameter or body field for tenant isolation\.$/m,
  "Tenant authorisation is enforced by `requireAuth` in `apps/control-api/src/auth/auth-guards.ts`,\n" +
    "which resolves the tenant from the record and rejects a mismatch with `HAF-1010`.\n" +
    "System-admin and public-webhook routes are exempt; see that file for the exact sets.",
);

if (asCheck) {
  if (next !== doc) {
    console.error(
      `docs/API-REFERENCE.md is stale: it documents ${operations.length} operations in the spec ` +
        `but the file does not match a fresh generation.\n` +
        `Run:  npm run docs:api-reference`,
    );
    process.exit(1);
  }
  console.log(`docs/API-REFERENCE.md is current: ${operations.length} operations / ${paths.size} paths.`);
} else {
  writeFileSync(DOC, next);
  console.log(`docs/API-REFERENCE.md written: ${operations.length} operations / ${paths.size} paths, ${byTag.size} groups.`);
}
